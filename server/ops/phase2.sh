#!/usr/bin/env bash
set -euo pipefail
umask 077
test "$EUID" -eq 0
ops=$(cd -- "$(dirname -- "$0")" && pwd)
install -d -m 0700 "${ops%/*}/assets"
asset="${ops%/*}/assets/ntfy_2.38.1_linux_amd64.tar.gz"
if [[ ! -f $asset ]]; then
    curl -fsSL --retry 2 --max-time 90 https://github.com/binwiederhier/ntfy/releases/download/v2.38.1/ntfy_2.38.1_linux_amd64.tar.gz -o "$asset"
fi
printf '%s  %s\n' 9727d45e5da86c3f338f0f329044485bddde76f3fbbbc3f9e695c14776f09c32 "$asset" | sha256sum --check
tar -xOf "$asset" ntfy_2.38.1_linux_amd64/ntfy > "${ops%/*}/assets/ntfy-axis"
install -m 0755 "${ops%/*}/assets/ntfy-axis" /usr/local/bin/ntfy-axis
getent passwd ntfy-axis >/dev/null || useradd --system --user-group --home-dir /var/lib/ntfy-axis --shell /usr/sbin/nologin ntfy-axis
install -d -m 0755 /etc/ntfy-axis
install -d -o ntfy-axis -g ntfy-axis -m 0750 /var/lib/ntfy-axis
install -m 0644 "$ops/ntfy-axis.yml" /etc/ntfy-axis/server.yml

secrets=/etc/ntfy-axis/.env
if [[ ! -e $secrets ]]; then
    python3 -W ignore::DeprecationWarning - "$secrets" <<'PY'
import crypt
import secrets
import string
import sys

password_hash = crypt.crypt(secrets.token_urlsafe(32), crypt.mksalt(crypt.METHOD_BLOWFISH))
if not password_hash.startswith("$2"):
    raise SystemExit("Could not generate bcrypt hash")
token = "tk_" + "".join(secrets.choice(string.ascii_lowercase + string.digits) for _ in range(29))
with open(sys.argv[1], "x", encoding="ascii") as target:
    target.write(f"NTFY_AUTH_USERS='axis:{password_hash}:user'\nNTFY_AUTH_TOKENS='axis:{token}'\n")
PY
fi
[[ $(stat -c '%u:%a' "$secrets") == 0:600 ]]
if ! grep -q '^AXIS_NTFY_TOKEN=' /etc/axis/.env; then
    # Both files are root-owned and generated by the deploy scripts.
    source "$secrets"
    printf 'AXIS_NTFY_TOKEN=%s\n' "${NTFY_AUTH_TOKENS#axis:}" >> /etc/axis/.env
fi
install -m 0644 "$ops/ntfy-axis.service" /etc/systemd/system/ntfy-axis.service
systemctl daemon-reload
systemctl enable ntfy-axis.service
systemctl restart ntfy-axis.service
curl -fsS --retry 4 --retry-all-errors http://127.0.0.1:2586/v1/health
printf '\n'
bash "$ops/deploy.sh"
